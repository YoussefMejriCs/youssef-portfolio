// Nav
document.addEventListener('DOMContentLoaded', function () {
  const navToggle = document.getElementById('nav-toggle');
  const mobileOverlay = document.getElementById('mobile-nav-overlay');
  const mobileLinks = mobileOverlay.querySelectorAll('a');

  navToggle.addEventListener('click', function () {
    mobileOverlay.classList.toggle('open');
    const icon = navToggle.querySelector('i');
    if (mobileOverlay.classList.contains('open')) {
      icon.className = 'fas fa-times';
    } else {
      icon.className = 'fas fa-bars';
    }
  });

  mobileLinks.forEach(link => {
    link.addEventListener('click', function () {
      mobileOverlay.classList.remove('open');
      navToggle.querySelector('i').className = 'fas fa-bars';
    });
  });

  // Nav scroll effect
  const nav = document.querySelector('.nav');
  let lastScroll = 0;
  window.addEventListener('scroll', function () {
    const current = window.pageYOffset;
    if (current > 50) {
      nav.classList.add('scrolled');
    } else {
      nav.classList.remove('scrolled');
    }
    lastScroll = current;
  });

  // Active nav link
  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-links a:not(.lang-toggle)');

  function updateActiveLink() {
    let currentSection = '';
    sections.forEach(section => {
      const top = section.offsetTop - 150;
      const bottom = top + section.offsetHeight;
      if (window.pageYOffset >= top && window.pageYOffset < bottom) {
        currentSection = section.getAttribute('id');
      }
    });

    navLinks.forEach(link => {
      link.classList.remove('active');
      if (link.getAttribute('href') === '#' + currentSection) {
        link.classList.add('active');
      }
    });
  }

  window.addEventListener('scroll', updateActiveLink);
  updateActiveLink();

  // Scroll animations
  const animElements = document.querySelectorAll('.fade-in, .fade-in-left, .fade-in-right');

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, {
    threshold: 0.1,
    rootMargin: '0px 0px -50px 0px'
  });

  animElements.forEach(el => observer.observe(el));

  // Contact form
  const form = document.getElementById('contact-form');
  const submitBtn = document.getElementById('form-submit');
  const formMessage = document.getElementById('form-message');

  if (form) {
    form.addEventListener('submit', async function (e) {
      e.preventDefault();

      const name = document.getElementById('form-name').value.trim();
      const email = document.getElementById('form-email').value.trim();
      const message = document.getElementById('form-message-text').value.trim();

      // Validation
      let valid = true;
      document.querySelectorAll('.form-input').forEach(el => el.classList.remove('error'));

      if (!name) {
        document.getElementById('form-name').classList.add('error');
        valid = false;
      }
      if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
        document.getElementById('form-email').classList.add('error');
        valid = false;
      }
      if (!message) {
        document.getElementById('form-message-text').classList.add('error');
        valid = false;
      }

      if (!valid) return;

      submitBtn.disabled = true;
      submitBtn.textContent = translations[currentLang]['contact-form-sending'];
      formMessage.className = 'form-message';
      formMessage.style.display = 'none';

      try {
        const res = await fetch('https://formspree.io/f/mojopnla', {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Accept': 'application/json'
          },
          body: JSON.stringify({ name, email, message })
        });

        if (res.ok) {
          formMessage.className = 'form-message success';
          formMessage.textContent = translations[currentLang]['contact-form-success'];
          formMessage.style.display = 'block';
          form.reset();
        } else {
          throw new Error('Formspree error');
        }
      } catch (err) {
        formMessage.className = 'form-message error';
        formMessage.textContent = translations[currentLang]['contact-form-error'];
        formMessage.style.display = 'block';
      } finally {
        submitBtn.disabled = false;
        submitBtn.textContent = translations[currentLang]['contact-form-send'];
      }
    });
  }

  // Language
  try {
    const saved = localStorage.getItem('portfolio-lang');
    if (saved === 'en' || saved === 'fr') {
      setLanguage(saved);
    } else {
      setLanguage('en');
    }
  } catch (e) {
    setLanguage('en');
  }
});
